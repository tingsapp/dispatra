// Real trial signup against a local API backed by a disposable database.
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const origin = process.env.E2E_ORIGIN || 'http://127.0.0.1:3005';
assert.ok(['localhost','127.0.0.1'].includes(new URL(origin).hostname));
assert.equal(process.env.E2E_DISPOSABLE, 'true', 'Use a disposable API database.');
const browser = await chromium.launch({channel:'chrome',headless:true});
const slug = 'trial-' + Date.now().toString(36);
const email = slug + '@example.com';
const password = 'Trial-password-123!';
const errors = [];
try {
  const context = await browser.newContext({viewport:{width:1440,height:1000}});
  await context.route('**/*', route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
  const page = await context.newPage();
  page.setDefaultTimeout(60000);
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin, {waitUntil:'domcontentloaded',timeout:60000});
  const company = page.getByLabel('Workspace', { exact: true });
  assert.equal(await company.inputValue(), '');
  await company.fill('admin');
  await page.getByRole('button',{name:'Start trial',exact:true}).click();
  await page.getByRole('alert').waitFor();
  await company.fill(slug);
  await page.screenshot({path:'/tmp/dispatra-trial-home-desktop.png',fullPage:true});
  await company.press('Enter');
  await page.waitForURL(origin + '/signup?company=' + slug);
  await page.getByRole('heading',{name:'Monthly plan'}).waitFor();
  await page.screenshot({path:'/tmp/dispatra-trial-plans-desktop.png',fullPage:true});
  for (const width of [390,320]) {
    await page.setViewportSize({width,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth),false);
    await page.screenshot({path:'/tmp/dispatra-trial-plans-'+width+'.png',fullPage:true});
  }
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'Start free trial',exact:true}).click();
  await page.getByRole('dialog',{name:'Start your free trial'}).waitFor();
  await page.keyboard.press('Escape');
  await page.waitForFunction(()=>document.activeElement?.textContent?.includes('Start free trial'));
  await page.getByRole('button',{name:'Start free trial',exact:true}).press('Enter');
  await page.getByRole('dialog',{name:'Start your free trial'}).waitFor();
  await page.keyboard.press('Shift+Tab');
  assert.equal(await page.getByRole('dialog').evaluate(el=>el.contains(document.activeElement)),true);
  assert.equal(await page.getByLabel('Workspace', { exact: true }).inputValue(), slug);
  await page.getByLabel('Company name',{exact:true}).fill('Trial Signup Company');
  await page.getByLabel('Full name',{exact:true}).fill('Trial Dispatcher');
  await page.getByLabel('Email',{exact:true}).fill(email);
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByLabel('Confirm password',{exact:true}).fill('different-password');
  await page.getByRole('checkbox',{name:/I agree to the Terms and Conditions/}).check();
  await page.getByRole('button',{name:'Start trial',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'Passwords do not match.'}).waitFor();
  await page.getByLabel('Confirm password',{exact:true}).fill(password);
  await page.screenshot({path:'/tmp/dispatra-trial-signup-desktop.png',fullPage:true});
  for (const width of [390,320]) {
    await page.setViewportSize({width,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth),false);
    assert.ok(await page.getByRole('button',{name:'Start trial',exact:true}).isVisible());
    if (width === 390) await page.screenshot({path:'/tmp/dispatra-trial-signup-mobile.png',fullPage:true});
  }
  await page.setViewportSize({width:1440,height:1000});
  const response = page.waitForResponse(r => r.url().endsWith('/api/v1/auth/signup') && r.request().method() === 'POST');
  await page.getByRole('button',{name:'Start trial',exact:true}).click();
  const created = await response;
  if (created.status() !== 201) throw new Error('Signup failed: HTTP ' + created.status());
  await page.waitForURL(origin + '/signup/verify');
  await page.getByLabel('Verification code').waitFor();
  for (const width of [1440,390,320]) {
    await page.setViewportSize({width,height:width===1440?1000:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.screenshot({path:'/tmp/dispatra-email-verification-'+width+'.png',animations:'disabled'});
  }
  await page.setViewportSize({width:1440,height:1000});
  assert.equal((await context.request.get(origin + '/api/v1/auth/me')).status(),401);
  assert.ok(process.env.E2E_VERIFICATION_CODE_URL, 'Use an isolated test-mail capture endpoint.');
  const mailUrl = new URL(process.env.E2E_VERIFICATION_CODE_URL);
  assert.ok(['localhost','127.0.0.1'].includes(mailUrl.hostname));
  mailUrl.searchParams.set('email',email);
  const mail = await context.request.get(mailUrl.toString());
  const delivered = await mail.json();
  assert.equal(delivered.recipient,email);
  await page.getByLabel('Verification code').fill(delivered.code);
  const verified = page.waitForResponse(r=>r.url().endsWith('/api/v1/auth/verification/confirm'));
  await page.getByRole('button',{name:'Verify email',exact:true}).click();
  assert.equal((await verified).status(),200);
  await page.waitForURL(origin + '/' + slug + '/');
  const accountResponse = await context.request.get(origin + '/api/v1/auth/me');
  assert.equal(accountResponse.status(),200);
  const account = await accountResponse.json();
  assert.equal(account.role,'DISPATCHER');
  assert.equal(account.organization.slug,slug);
  assert.equal(new Date(account.organization.trial_ends_at)-new Date(account.organization.trial_started_at),30*24*60*60*1000);
  await page.waitForURL(origin + '/' + slug + '/');
  await page.getByRole('button',{name:'Dispatcher Account',exact:true}).waitFor();
  const me = await context.request.get(origin + '/api/v1/auth/me');
  assert.equal(me.status(),200);
  assert.equal((await me.json()).id,account.id);
  const stored = await page.evaluate(()=>Object.values(localStorage).concat(Object.values(sessionStorage)).join(' '));
  assert.equal(stored.includes(password),false);
  await page.getByRole('button',{name:'Dispatcher Account',exact:true}).click();
  await page.getByRole('menuitem',{name:'Logout',exact:true}).click();
  await page.waitForURL(origin + '/login');
  await page.getByLabel('Email',{exact:true}).fill(email);
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.waitForURL(origin + '/' + slug + '/');
  assert.equal(errors.length,0,errors.join('\n'));
  console.log('PASS: homepage → plans → signup → emailed-code verification → 30-day workspace, confirmation, login/logout, password privacy and mobile layouts.');
} finally {await browser.close();}
